"""Python client for the Nemau Cloud public API.

The client calls the Nemau Cloud API under ``/api/v1``, the same API the web
console uses.

Writes are asynchronous. A create, a delete or an action answers ``202`` with a
:class:`~nemau.models.TaskRef`, and the platform does the work in the
background. :meth:`~nemau.client.NemauClient.wait_for` waits until the task
finishes, and the ``..._and_wait`` variants do both steps.

The organization comes from the credential. The project comes from the
``project`` argument, then from :data:`~nemau.auth.ENV_PROJECT`, and from the
credential otherwise. :meth:`~nemau.client.NemauClient.for_project` returns a
client for another project.

Example::

    from nemau import NemauClient

    nemau = NemauClient()                       # reads the environment
    instance = nemau.compute.create_instance_and_wait(
        name="web-1",
        image_id="ubuntu-24.04",
        vcpus=2,
        ram_mb=4096,
        disk_gb=40,
    )
    print(instance.id, instance.status, instance.addresses)
"""

